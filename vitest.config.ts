import { defineConfig } from 'vitest/config'

// Сквозные тесты живут в e2e/ и запускаются Playwright'ом. Без явного include
// vitest подбирает и их, а playwright-спека в его окружении падает с «did not
// expect test() to be called here» — прогон краснеет там, где всё исправно.
export default defineConfig({
  test: {
    include: ['src/**/*.test.ts'],
    coverage: {
      provider: 'v8',
      // lcov.info ждёт codecov-action в CI. По умолчанию v8-провайдер отдаёт
      // html/clover/json — lcov.info среди них нет, и загрузка покрытия молча
      // ничего не находила: fail_ci_if_error: false это прятал.
      reporter: ['text', 'lcov'],
      // ЯВНЫЙ СПИСОК ФАЙЛОВ, А НЕ «ЧТО ЗАГРУЗИЛОСЬ».
      //
      // По умолчанию v8-провайдер отчитывается только о модулях, которые тест
      // реально импортировал. Тест здесь один — целостность данных, — поэтому
      // в отчёт попадали пять JSON и больше ничего: код в src/islands/ не
      // просто был непокрыт, его в отчёте не существовало. Порог patch 70% в
      // codecov.yml при этом всегда зелёный, потому что судить не о чем, а
      // бейдж в README мерил покрытие JSON-литералов.
      //
      // С include непокрытый модуль честно показывает 0% и тянет цифру вниз —
      // это и есть смысл бейджа.
      include: ['src/**/*.ts'],
    },
  },
})
