import { test, expect } from './guards';

// Меню отрисовывается на КАЖДОЙ странице, а секции, на которые оно ссылается,
// есть только на главной. Пока адреса в Nav.astro были относительными (#path),
// клик по меню с любой внутренней страницы лишь дописывал хеш к текущему адресу
// и никуда не вёл.
//
// Ни один существующий гейт этого не видел: линк-чекер в ci.yml пропускает всё
// с `#`, а тест якорей в home.spec.ts ходит только по главной. Отсюда отдельный
// файл — проверка нужна именно с внутренней страницы.
test.describe('меню с внутренней страницы', () => {
  for (const [label, id] of [
    ['Путь', 'path'],
    ['Работа', 'work'],
    ['Pet-проекты', 'pet'],
    ['Контакты', 'contact'],
  ] as const) {
    test(`«${label}» уводит на секцию главной`, async ({ page }) => {
      await page.goto('/projects/chillhub/');

      await page.locator('.site-nav .links').getByRole('link', { name: label }).click();

      // Адрес сверяется целиком, а не хвостом: `/projects/chillhub/#path` —
      // ровно то, что получалось со сломанным меню, — тоже кончается на «/#path».
      await expect(page).toHaveURL(`/#${id}`);
      // Адрес — половина дела: секция обязана реально оказаться в кадре.
      await expect(page.locator(`section#${id}`)).toBeInViewport({ ratio: 0.1 });
    });
  }
});
