import { test, expect } from './guards';

// Единственный сетевой побочный эффект сайта — пустой POST на /e/<событие>.
// До этого файла он не проверялся нигде: в проде путь обслуживает nginx, на
// `astro preview` его нет, и guards.ts просто прощал 404 — то есть отсутствие
// запроса и сломанный запрос выглядели одинаково. Проверяется именно факт
// запроса, а не ответ: счётчик ответ не читает, и что отдаст локальный
// сервер — неважно.
//
// НАБЛЮДЕНИЕ, А НЕ ПОДМЕНА. page.route включает перехват всей сети страницы,
// а не одного шаблона: остальные запросы пропускаются через ту же машинерию
// и заметно замедляются. Переходы идут через ClientRouter, а он подгружает
// страницу заранее, по наведению курсора, — из-за задержки предзагрузка не
// успевала завершиться до клика, браузер её обрывал, и постоянный наблюдатель
// за сетью валил тест на неудавшемся запросе самого перехода. Пассивного
// слушателя достаточно: он видит sendBeacon так же, как обычный запрос, и
// показывает и метод, и адрес, ничего не замедляя.
test.describe('счётчики событий', () => {
  test('переход в карточку pet-проекта считается', async ({ page }) => {
    const beacons: string[] = [];
    page.on('request', (req) => {
      const { pathname } = new URL(req.url());
      if (pathname.startsWith('/e/')) beacons.push(`${req.method()} ${pathname}`);
    });

    await page.goto('/');
    await page
      .locator('#pet article.card')
      .first()
      .getByRole('link', { name: 'Подробнее →' })
      .click();
    await expect(page).toHaveURL(/\/projects\/chillhub\/$/);

    // Событие уходит рядом с переходом, поэтому ждём его, а не читаем сразу.
    await expect.poll(() => beacons).toContain('POST /e/project_open');
  });
});
